const dir = path.join(process.cwd(), "movies");
const files = fs.readdirSync(dir).filter((file) => file.endsWith(".md"));
const slugs = new Set(files.map((file) => file.replace(/\.md$/, "")));
const missing = [...slugs].filter((slug) => !THEMES[slug]);
const unknown = Object.keys(THEMES).filter((slug) => !slugs.has(slug));
if (missing.length || unknown.length) throw new Error(`mapping mismatch: missing=${missing.join(",")} unknown=${unknown.join(",")}`);

for (const file of files) {
  const slug = file.replace(/\.md$/, "");
  const filePath = path.join(dir, file);
  const raw = fs.readFileSync(filePath, "utf8");
  const line = `themes: [${THEMES[slug].join(", ")}]`;
  const out = /^themes:/m.test(raw)
    ? raw.replace(/^themes:.*$/m, line)
    : /^body_kind:/m.test(raw)
      ? raw.replace(/^body_kind:/m, `${line}\nbody_kind:`)
      : raw.replace(/^date:/m, `${line}\ndate:`);
  fs.writeFileSync(filePath, out);
}

